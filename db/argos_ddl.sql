-- 센서 14개(TE 5 · IT 5 · AT 3 · IR 1), 관제 단위 5개(전처리 · 전착 탱크 · 전착 · 중도 · 상도 건조로)
-- 설정온도·정상 평균 전류는 7일 더미데이터(paint_7days)의 센서별 평균 기준입니다.
