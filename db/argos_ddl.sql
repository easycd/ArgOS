-- ───────────── 1) 테이블 ─────────────

-- 사업장: 공장이 모여 있는 지역 단위(울산·아산·전주). 사업장 선택 화면의 지도 핀 하나가 한 줄.
CREATE TABLE plant (
    plant_id             smallint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name                 varchar(30) NOT NULL UNIQUE,
    code                 varchar(10) NOT NULL UNIQUE,
    address              varchar(200),
    lat                  numeric(9,6),
    lng                  numeric(9,6),
    map_file_id          bigint,
    CONSTRAINT pk_plant PRIMARY KEY (plant_id)
);

-- 공장 (1~5공장): 사업장 안의 공장 건물 단위. 사업장과 공정 사이 단계.
CREATE TABLE factory (
    factory_id           smallint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    plant_id             smallint NOT NULL,
    code                 varchar(10) NOT NULL,
    name                 varchar(30) NOT NULL,
    map_shape            jsonb,
    sort_order           smallint,
    CONSTRAINT pk_factory PRIMARY KEY (factory_id)
);

-- 공정: 공장별 공정(프레스·차체·도장·의장·검사·공통). 센서 태그 앞자리(1xx~9xx)와 대응.
CREATE TABLE process (
    process_id           smallint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    factory_id           smallint NOT NULL,
    code                 varchar(10) NOT NULL,
    name                 varchar(30) NOT NULL,
    tag_prefix           smallint,
    floorplan_file_id    bigint,
    CONSTRAINT pk_process PRIMARY KEY (process_id),
    CONSTRAINT uq_process_factory_code UNIQUE (factory_id, code)
);

-- 설비: 공정에 속한 설비(건조로, 소각설비, 순환 펌프 등). 배치도 좌표를 가진다.
CREATE TABLE equipment (
    equipment_id         int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    process_id           smallint NOT NULL,
    code                 varchar(30) NOT NULL,
    name                 varchar(60) NOT NULL,
    pos_x                numeric(8,2),
    pos_y                numeric(8,2),
    equipment_type       varchar(20),
    shape                varchar(12),
    size_w               numeric(8,2),
    size_d               numeric(8,2),
    size_h               numeric(8,2),
    pos_z                numeric(8,2),
    is_active            boolean NOT NULL DEFAULT true,
    run_state            varchar(10) CHECK (run_state IN ('RUN', 'STANDBY')),
    fan_rpm              int,
    CONSTRAINT pk_equipment PRIMARY KEY (equipment_id),
    CONSTRAINT uq_equipment_process_code UNIQUE (process_id, code)
);

-- 센서(태그): 센서·계측 태그 한 개가 한 행. 온도(TE)·전류(IT)·CO(AT)·열화상(IR).
CREATE TABLE sensor (
    sensor_id            int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    tag                  varchar(20) NOT NULL UNIQUE,
    equipment_id         int NOT NULL,
    sensor_type          varchar(4) NOT NULL CHECK (sensor_type IN ('TE', 'IT', 'AT', 'IR')),
    unit                 varchar(8),
    connection           varchar(4) NOT NULL CHECK (connection IN ('PLC', 'GW', 'VMS')),
    sample_sec           smallint NOT NULL DEFAULT 5,
    setpoint             numeric,
    is_active            boolean NOT NULL DEFAULT true,
    CONSTRAINT pk_sensor PRIMARY KEY (sensor_id)
);

-- 센서 기준값: 센서별 단계 기준값과 지속 조건. 변경 이력을 valid_from/valid_to 로 남기며, 센서당 현재 적용 행은 하나(valid_to IS NULL).
CREATE TABLE sensor_threshold (
    threshold_id         int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    sensor_id            int NOT NULL,
    warn_value           numeric,
    alarm_value          numeric,
    low_warn             numeric,
    low_alarm            numeric,
    rate_per_min         numeric,
    warn_samples         smallint NOT NULL DEFAULT 6,
    alarm_samples        smallint NOT NULL DEFAULT 3,
    recover_samples      smallint NOT NULL DEFAULT 6,
    basis                varchar(10) NOT NULL DEFAULT 'PROPOSED' CHECK (basis IN ('STANDARD', 'PROPOSED')),
    note                 varchar(200),
    valid_from           timestamptz NOT NULL DEFAULT now(),
    valid_to             timestamptz,
    changed_by           int,
    season               varchar(12) NOT NULL DEFAULT 'ALL' CHECK (season IN ('ALL', 'SPRING_FALL', 'SUMMER', 'WINTER')),
    CONSTRAINT pk_sensor_threshold PRIMARY KEY (threshold_id),
    CONSTRAINT ck_threshold_valid CHECK (valid_to IS NULL OR valid_to > valid_from)
);

-- 권한: 사용자 권한 종류. 계정 3종(작업자 / 공장 관리자 / 본사 관리자).
CREATE TABLE role (
    role_id              smallint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code                 varchar(20) NOT NULL UNIQUE,
    name                 varchar(30) NOT NULL,
    CONSTRAINT pk_role PRIMARY KEY (role_id)
);

-- 사용자: 웹 화면·담당자 앱 사용자 계정.
CREATE TABLE app_user (
    user_id              int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    plant_id             smallint,
    role_id              smallint NOT NULL,
    login_id             varchar(40) NOT NULL UNIQUE,
    password_hash        varchar(100) NOT NULL,
    name                 varchar(40) NOT NULL,
    phone                varchar(20),
    fcm_token            varchar(300),
    is_active            boolean NOT NULL DEFAULT true,
    pw_reset_required    boolean NOT NULL DEFAULT false,
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz,
    CONSTRAINT pk_app_user PRIMARY KEY (user_id)
);

-- 담당 범위: 사용자가 어느 공장·공정을 맡는지. 한 사람이 여러 줄을 가질 수 있다.
CREATE TABLE user_assignment (
    assignment_id        int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id              int NOT NULL,
    plant_id             smallint,
    factory_id           smallint,
    process_id           smallint,
    created_at           timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_user_assignment PRIMARY KEY (assignment_id)
);

-- 로그인 이력: 로그인 시도(성공·실패) 이력.
CREATE TABLE login_history (
    login_id_seq         bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id              int NOT NULL,
    logged_at            timestamptz NOT NULL DEFAULT now(),
    ip_addr              inet,
    success              boolean NOT NULL,
    CONSTRAINT pk_login_history PRIMARY KEY (login_id_seq)
);

-- 근무조 (선택): 주간·야간 근무 시간. 근무조 시간을 바꿀 수 있게 할 때만 쓴다.
CREATE TABLE work_shift (
    shift_id             smallint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    plant_id             smallint NOT NULL,
    name                 varchar(10) NOT NULL,
    start_time           time NOT NULL,
    end_time             time NOT NULL,
    CONSTRAINT pk_work_shift PRIMARY KEY (shift_id)
);

-- 안전 등급: 공장별 월 안전 등급(A·B·C).
CREATE TABLE safety_grade (
    factory_id           smallint NOT NULL,
    month                date NOT NULL,
    grade                char(1) NOT NULL CHECK (grade IN ('A', 'B', 'C')),
    score                numeric,
    CONSTRAINT pk_safety_grade PRIMARY KEY (factory_id, month)
);

-- 설비 담당자: 설비별로 지정한 담당자. 설비 하나에 여러 명.
CREATE TABLE equipment_manager (
    equipment_id         int NOT NULL,
    user_id              int NOT NULL,
    is_primary           boolean NOT NULL DEFAULT false,
    CONSTRAINT pk_equipment_manager PRIMARY KEY (equipment_id, user_id)
);

-- 관제 단위 (예: 전착 건조로): 화재·가스 판정을 묶어서 하는 단위. 도장 공정은 전착·중도·상도 건조로 3개.
CREATE TABLE control_unit (
    unit_id              smallint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    process_id           smallint NOT NULL,
    equipment_id         int NOT NULL,
    name                 varchar(30) NOT NULL,
    is_active            boolean NOT NULL DEFAULT true,
    CONSTRAINT pk_control_unit PRIMARY KEY (unit_id)
);

-- 관제 단위 구성 센서: 관제 단위에 속한 센서와 어느 사고 판정에 쓰는지. 화재는 TE·IT·IR, 가스는 IT·AT.
CREATE TABLE control_unit_sensor (
    unit_id              smallint NOT NULL,
    sensor_id            int NOT NULL,
    hazard               varchar(4) NOT NULL CHECK (hazard IN ('FIRE', 'GAS')),
    CONSTRAINT pk_control_unit_sensor PRIMARY KEY (unit_id, sensor_id, hazard)
);

-- 파일: 열화상 이미지·서류 스캔 원본의 파일 정보. 실제 파일은 파일 저장소에 두고 경로만 저장.
CREATE TABLE file_asset (
    file_id              bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    kind                 varchar(12) NOT NULL CHECK (kind IN ('THERMAL', 'DOC_SCAN', 'FLOORPLAN', 'REPORT')),
    path                 varchar(300) NOT NULL,
    mime                 varchar(60),
    size_bytes           bigint,
    created_at           timestamptz NOT NULL DEFAULT now(),
    sensor_id            int,
    captured_at          timestamptz,
    meta                 jsonb,
    CONSTRAINT pk_file_asset PRIMARY KEY (file_id)
);

-- 센서 추이(1분): 센서별 1분 평균·최소·최대. 5초 원시값은 저장하지 않는다. 월별 RANGE 파티션(ts).
CREATE TABLE sensor_trend (
    sensor_id            int NOT NULL,
    ts                   timestamptz NOT NULL,
    avg_v                numeric NOT NULL,
    min_v                numeric NOT NULL,
    max_v                numeric NOT NULL,
    n                    smallint NOT NULL,
    CONSTRAINT pk_sensor_trend PRIMARY KEY (sensor_id, ts)
);

-- 임계값 초과 이벤트: 임계값 조건(임계값+지속시간)을 충족한 구간을 한 건으로 기록.
CREATE TABLE sensor_event (
    event_id             bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    sensor_id            int NOT NULL,
    threshold_id         int NOT NULL,
    stage                smallint NOT NULL CHECK (stage IN (2, 3)),
    rule                 varchar(10) NOT NULL CHECK (rule IN ('ABS', 'RATE', 'DURATION', 'COMPOUND')),
    started_at           timestamptz NOT NULL,
    ended_at             timestamptz,
    peak_value           numeric,
    CONSTRAINT pk_sensor_event PRIMARY KEY (event_id),
    CONSTRAINT ck_event_period CHECK (ended_at IS NULL OR ended_at >= started_at)
);

-- 이벤트 원시 샘플: 이벤트 전후의 5초 원시 샘플. 분석·재현용(선택).
CREATE TABLE sensor_event_sample (
    event_id             bigint NOT NULL,
    ts                   timestamptz NOT NULL,
    value                numeric,
    CONSTRAINT pk_sensor_event_sample PRIMARY KEY (event_id, ts)
);

-- 경보: 관제 단위(건조로)에서 사고 종류(화재·가스)별로 발생한 경보 한 건. 단위 안 센서 하나라도 2단계면 2단계, 하나라도 3단계면 3단계.
CREATE TABLE alarm (
    alarm_id             bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    unit_id              smallint NOT NULL,
    stage                smallint NOT NULL CHECK (stage IN (2, 3)),
    hazard               varchar(4) NOT NULL CHECK (hazard IN ('FIRE', 'GAS')),
    thermal_file         bigint,
    raised_at            timestamptz NOT NULL DEFAULT now(),
    status               varchar(10) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'ACKED', 'ACTING', 'CLOSED')),
    acked_by             int,
    acked_at             timestamptz,
    closed_at            timestamptz,
    closed_by            int,
    CONSTRAINT pk_alarm PRIMARY KEY (alarm_id)
);

-- 경보 판정 근거: 경보를 만든 센서 이벤트 목록. 경보 하나에 이벤트 여럿(여러 센서).
CREATE TABLE alarm_event (
    alarm_id             bigint NOT NULL,
    event_id             bigint NOT NULL,
    CONSTRAINT pk_alarm_event PRIMARY KEY (alarm_id, event_id)
);

-- 경보 조치 이력: 경보별 조치(푸시·방송·셧다운·체크리스트·수기 메모) 이력.
CREATE TABLE alarm_action (
    action_id            bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    alarm_id             bigint NOT NULL,
    action               varchar(20) NOT NULL CHECK (action IN ('PUSH', 'BROADCAST', 'SHUTDOWN', 'CHECKLIST', 'MANUAL_NOTE', 'ACK', 'REASSIGN', 'EVACUATED')),
    target               varchar(40),
    result               varchar(10) CHECK (result IN ('OK', 'FAIL', 'PENDING')),
    detail               varchar(500),
    user_id              int,
    done_at              timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_alarm_action PRIMARY KEY (action_id)
);

-- 설비 제어 명령: 설비에 보낸 명령과 응답. 배기팬 가동·RPM 변경 요청과 응답.
CREATE TABLE equipment_command (
    command_id           bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    equipment_id         int NOT NULL,
    alarm_id             bigint,
    command              varchar(12) NOT NULL CHECK (command IN ('FAN_ON', 'FAN_RPM')),
    value                numeric,
    result               varchar(10) NOT NULL DEFAULT 'PENDING' CHECK (result IN ('PENDING', 'OK', 'FAIL')),
    requested_by         int NOT NULL,
    requested_at         timestamptz NOT NULL DEFAULT now(),
    completed_at         timestamptz,
    CONSTRAINT pk_equipment_command PRIMARY KEY (command_id)
);

-- 화재: 화재로 판정된 사건 한 건. 위치, 경고 방송, 본사 통보, 비밀번호 해제를 담는다.
CREATE TABLE fire_incident (
    fire_id              bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    alarm_id             bigint NOT NULL,
    plant_id             smallint NOT NULL,
    process_id           smallint NOT NULL,
    equipment_id         int,
    pos_x                numeric(8,2),
    pos_y                numeric(8,2),
    max_temp             numeric(5,1),
    detected_at          timestamptz NOT NULL DEFAULT now(),
    broadcast_started_at timestamptz,
    broadcast_ended_at   timestamptz,
    hq_notified_at       timestamptz,
    unlock_fail_count    smallint NOT NULL DEFAULT 0,
    status               varchar(10) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'CLEARED')),
    cleared_by           int,
    cleared_at           timestamptz,
    CONSTRAINT pk_fire_incident PRIMARY KEY (fire_id)
);

-- 체크리스트 양식: 설비 종류·센서 종류별로 미리 정해 둔 원인 문구와 항목 목록. 보낼 때 여기서 복사한다.
CREATE TABLE checklist_template (
    template_id          int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    equipment_type       varchar(20) NOT NULL,
    sensor_type          varchar(4) NOT NULL,
    stage                smallint NOT NULL,
    cause                varchar(200) NOT NULL,
    items                jsonb NOT NULL,
    is_active            boolean NOT NULL DEFAULT true,
    CONSTRAINT pk_checklist_template PRIMARY KEY (template_id)
);

-- 체크리스트: 주의 경보 때 공정 담당자 앱으로 보낸 체크리스트 한 건. 전송 → 진행 → 완료 보고 → 확인.
CREATE TABLE checklist (
    checklist_id         int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    alarm_id             bigint NOT NULL,
    template_id          int,
    assignee_id          int NOT NULL,
    status               varchar(12) NOT NULL DEFAULT 'SENT' CHECK (status IN ('SENT', 'IN_PROGRESS', 'REPORTED', 'CONFIRMED', 'CANCELLED')),
    sent_by              int,
    sent_at              timestamptz NOT NULL DEFAULT now(),
    remind_count         smallint NOT NULL DEFAULT 0,
    last_remind_at       timestamptz,
    reported_at          timestamptz,
    confirmed_by         int,
    confirmed_at         timestamptz,
    CONSTRAINT pk_checklist PRIMARY KEY (checklist_id)
);

-- 체크리스트 항목: 체크리스트 안의 항목 하나. 완료 시각, 결과, 메모.
CREATE TABLE checklist_item (
    item_id              bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    checklist_id         int NOT NULL,
    seq                  smallint NOT NULL,
    content              varchar(200) NOT NULL,
    done_at              timestamptz,
    result               varchar(20),
    memo                 varchar(200),
    CONSTRAINT pk_checklist_item PRIMARY KEY (item_id)
);

-- 점검 일정: 설비별 점검 일정과 담당자.
CREATE TABLE inspection_schedule (
    schedule_id          int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    equipment_id         int NOT NULL,
    assignee_id          int,
    planned_at           date NOT NULL,
    status               varchar(10) NOT NULL DEFAULT 'PLANNED' CHECK (status IN ('PLANNED', 'DONE', 'OVERDUE')),
    done_at              timestamptz,
    title                varchar(100),
    done_by              int,
    CONSTRAINT pk_inspection_schedule PRIMARY KEY (schedule_id)
);

-- 서류 양식: F01~F05 서류마다 인식할 항목과 위치를 정의한 것.
CREATE TABLE doc_form (
    form_type            varchar(30) NOT NULL,
    name                 varchar(60) NOT NULL,
    field_schema         jsonb NOT NULL,
    version              smallint NOT NULL DEFAULT 1,
    CONSTRAINT pk_doc_form PRIMARY KEY (form_type)
);

-- 서류 인식 결과: 수기 점검 서류를 인식(OCR)한 결과. 양식별 항목 값은 JSON으로 저장.
CREATE TABLE ocr_result (
    ocr_id               bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    schedule_id          int,
    file_id              bigint NOT NULL,
    form_type            varchar(30) NOT NULL,
    fields               jsonb NOT NULL,
    confidence           numeric(4,3),
    reviewed_by          int,
    recognized_at        timestamptz NOT NULL DEFAULT now(),
    status               varchar(12) NOT NULL DEFAULT 'UPLOADED' CHECK (status IN ('UPLOADED', 'RECOGNIZING', 'REVIEW', 'DONE')),
    uploaded_by          int,
    process_id           smallint,
    CONSTRAINT pk_ocr_result PRIMARY KEY (ocr_id)
);

-- 채팅: 점검 현황 채팅 (본사 ↔ 공장).
CREATE TABLE chat_message (
    msg_id               bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    plant_id             smallint NOT NULL,
    sender_id            int NOT NULL,
    schedule_id          int,
    body                 varchar(1000) NOT NULL,
    sent_at              timestamptz NOT NULL DEFAULT now(),
    alarm_id             bigint,
    CONSTRAINT pk_chat_message PRIMARY KEY (msg_id)
);

-- 채팅 읽음: 사람마다 대화방에서 어디까지 읽었는지. 안 읽은 수 배지에 쓴다.
CREATE TABLE chat_read (
    user_id              int NOT NULL,
    plant_id             smallint NOT NULL,
    last_read_msg_id     bigint,
    updated_at           timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_chat_read PRIMARY KEY (user_id, plant_id)
);

-- 이용 로그: 사람이 시스템에서 한 일을 한 줄씩 남긴 기록. 기준값 변경, 설비 이동, 내보내기 등.
CREATE TABLE activity_log (
    log_id               bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id              int NOT NULL,
    plant_id             smallint,
    process_id           smallint,
    type                 varchar(20) NOT NULL,
    target_table         varchar(40),
    target_id            bigint,
    summary              varchar(200),
    before               jsonb,
    after                jsonb,
    ip_addr              inet,
    created_at           timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_activity_log PRIMARY KEY (log_id)
);

