-- ArgOS SHE 환경안전관제 — PostgreSQL DDL (33개 테이블)
-- 근거: ArgOS ERD v3 (파라미터 포함 버전)
-- 이 파일 하나로 실행: 1부 DDL(테이블·FK·인덱스·주석) → 2부 초기 데이터(INSERT)
-- 이름·타입은 제안값입니다. 백엔드(Spring Boot) 엔티티와 맞춘 뒤 확정하세요.
