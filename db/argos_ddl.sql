BEGIN;

INSERT INTO plant(name, code, address) VALUES ('울산', 'USN', '울산광역시');
INSERT INTO factory(plant_id, code, name, sort_order)
  SELECT plant_id, 'F5', '5공장', 5 FROM plant WHERE code='USN';
INSERT INTO process(factory_id, code, name, tag_prefix)
  SELECT factory_id, 'PAINT', '도장', 3 FROM factory WHERE code='F5';

-- 설비 (공정 안 설비 코드는 도면 이름 기준)
INSERT INTO equipment(process_id, code, name, equipment_type)
SELECT p.process_id, v.code, v.name, v.etype
FROM process p, (VALUES
  ('PRE-TANK',   '전처리 탱크',        '탱크'),
  ('PRE-PUMP',   '전처리 순환펌프',    '펌프'),
  ('ED-TANK',    '전착 탱크',          '탱크'),
  ('ED-PUMP',    '전착 순환펌프',      '펌프'),
  ('ED-OVEN',    '전착 건조로',        '건조로'),
  ('ED-FAN',     '전착 건조로 배기팬', '배기팬'),
  ('ED-BURNER',  '전착 건조로 버너실', '버너실'),
  ('MID-OVEN',   '중도 건조로',        '건조로'),
  ('MID-FAN',    '중도 건조로 배기팬', '배기팬'),
  ('MID-BURNER', '중도 건조로 버너실', '버너실'),
  ('TOP-OVEN',   '상도 건조로',        '건조로'),
  ('TOP-FAN',    '상도 건조로 배기팬', '배기팬'),
  ('TOP-BURNER', '상도 건조로 버너실', '버너실'),
  ('TOP-CAM',    '상도 건조로 외벽 열화상', 'CAMERA')
) AS v(code, name, etype)
WHERE p.code='PAINT';

-- 센서 (태그는 배치도 계장 목록 그대로). setpoint: TE=설정온도(℃), IT=정상 평균 전류(A), AT/IR=NULL
INSERT INTO sensor(tag, equipment_id, sensor_type, unit, connection, setpoint)
SELECT v.tag, e.equipment_id, v.stype, v.unit, v.conn, v.sp
FROM (VALUES
  ('TE-301','PRE-TANK',  'TE','℃','GW', 50.0),
  ('IT-301','PRE-PUMP',  'IT','A','GW', 24.0),
  ('TE-302','ED-TANK',   'TE','℃','GW', 28.0),
  ('IT-302','ED-PUMP',   'IT','A','GW', 12.0),
  ('TE-303','ED-OVEN',   'TE','℃','PLC',180.0),
  ('IT-303','ED-FAN',    'IT','A','PLC',25.5),
  ('AT-301','ED-BURNER', 'AT','ppm','PLC',NULL),
  ('TE-304','MID-OVEN',  'TE','℃','PLC',150.0),
  ('IT-305','MID-FAN',   'IT','A','PLC',22.0),
  ('AT-302','MID-BURNER','AT','ppm','PLC',NULL),
  ('TE-305','TOP-OVEN',  'TE','℃','PLC',140.0),
  ('IT-307','TOP-FAN',   'IT','A','PLC',25.5),
  ('AT-303','TOP-BURNER','AT','ppm','PLC',NULL),
  ('IR-301','TOP-CAM',   'IR','℃','VMS',NULL)
) AS v(tag, ecode, stype, unit, conn, sp)
JOIN equipment e ON e.code = v.ecode;

-- 임계값: 2단계 6회(30초) 연속, 3단계 3회(15초) 연속, 복귀 6회(30초) 연속 정상 — 모든 센서 동일
--  TE : 2단계 = 설정온도 +10 ℃, 3단계 = +20 ℃
--  IT : 2단계 = 정상평균 110%(상) / 90%(하), 3단계 = 125%(상) / 70%(하)
--  AT : 2단계 = 15 ppm, 3단계 = 30 ppm
--  IR : 2단계 = 50 ℃, 3단계 = 60 ℃
INSERT INTO sensor_threshold(sensor_id, warn_value, alarm_value, low_warn, low_alarm,
                             warn_samples, alarm_samples, recover_samples, basis, note)
SELECT s.sensor_id,
  CASE s.sensor_type WHEN 'TE' THEN s.setpoint+10 WHEN 'IT' THEN round(s.setpoint*1.10,2) WHEN 'AT' THEN 15 WHEN 'IR' THEN 50 END,
  CASE s.sensor_type WHEN 'TE' THEN s.setpoint+20 WHEN 'IT' THEN round(s.setpoint*1.25,2) WHEN 'AT' THEN 30 WHEN 'IR' THEN 60 END,
  CASE WHEN s.sensor_type='IT' THEN round(s.setpoint*0.90,2) END,
  CASE WHEN s.sensor_type='IT' THEN round(s.setpoint*0.70,2) END,
  6, 3, 6, 'PROPOSED',
  CASE s.sensor_type WHEN 'AT' THEN '3단계 30ppm은 60초 평균, 200ppm 이상은 즉시 3단계(판정 로직에서 처리)'
                     WHEN 'IT' THEN '정지(0 A 근처)가 10초 지속되면 즉시 3단계(판정 로직에서 처리)' END
FROM sensor s;

-- 관제 단위: 전처리 · 전착 탱크 · 전착/중도/상도 건조로 (설비 = 대표 설비)
INSERT INTO control_unit(process_id, equipment_id, name)
SELECT p.process_id, e.equipment_id, v.name
FROM process p, (VALUES ('PRE-TANK','전처리'),('ED-TANK','전착 탱크'),('ED-OVEN','전착 건조로'),('MID-OVEN','중도 건조로'),('TOP-OVEN','상도 건조로')) AS v(ecode,name)
JOIN equipment e ON e.code=v.ecode WHERE p.code='PAINT';

-- 관제 단위별 센서: 화재 = TE·IT(·IR), 가스 = IT·AT   (IT는 두 사고에 모두 사용)
-- 전처리·전착 탱크는 TE·IT만 있어 화재 판정만 한다 (두 센서 모두 이상이면 스팟 로봇이 적외선 카메라로 확인)
INSERT INTO control_unit_sensor(unit_id, sensor_id, hazard)
SELECT u.unit_id, s.sensor_id, h.hazard
FROM (VALUES
  ('전처리','TE-301','FIRE'),('전처리','IT-301','FIRE'),
  ('전착 탱크','TE-302','FIRE'),('전착 탱크','IT-302','FIRE'),
  ('전착 건조로','TE-303','FIRE'),('전착 건조로','IT-303','FIRE'),
  ('전착 건조로','IT-303','GAS'), ('전착 건조로','AT-301','GAS'),
  ('중도 건조로','TE-304','FIRE'),('중도 건조로','IT-305','FIRE'),
  ('중도 건조로','IT-305','GAS'), ('중도 건조로','AT-302','GAS'),
  ('상도 건조로','TE-305','FIRE'),('상도 건조로','IT-307','FIRE'),('상도 건조로','IR-301','FIRE'),
  ('상도 건조로','IT-307','GAS'), ('상도 건조로','AT-303','GAS')
) AS h(uname, tag, hazard)
JOIN control_unit u ON u.name=h.uname
JOIN sensor s ON s.tag=h.tag;

